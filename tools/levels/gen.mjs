// Writes level JSON files from levels.mjs (only missing files unless --force) and always rebuilds index.js.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LEVEL_DEFS } from './levels.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = path.join(root, 'src', 'data', 'levels');
fs.mkdirSync(dir, { recursive: true });
const force = process.argv.includes('--force');
let wrote = 0;
for (const lv of LEVEL_DEFS) {
  const f = path.join(dir, `${lv.id}.json`);
  if (fs.existsSync(f) && !force) continue;
  fs.writeFileSync(f, JSON.stringify(lv, null, 1).replace(/\n\s+(-?[\d.]+|"[^"]*")(,?)(?=\n)/g, ' $1$2') + '\n');
  wrote++;
}
writeIndex();
console.log(`levels: wrote ${wrote}, total ${LEVEL_DEFS.length}`);

export function writeIndex() {
  const files = fs.readdirSync(dir).filter((f) => /^L\d+\.json$/.test(f)).sort();
  const lines = ['// generated by tools/levels/gen.mjs — do not edit', ...files.map((f, i) => `import l${i} from './${f}';`),
    `export const LEVELS = [${files.map((_, i) => `l${i}`).join(', ')}];`, ''];
  fs.writeFileSync(path.join(dir, 'index.js'), lines.join('\n'));
}
