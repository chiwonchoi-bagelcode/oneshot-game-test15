import { openGame } from '../qa/shot.mjs';
import { SLOW_INIT, setupSlow, setRate, captureSegment } from './slowcap.mjs';
const g = await openGame({ page: 'dev.html?clean=1', w: 360, h: 640, dpr: 3 });
await g.context.addInitScript(SLOW_INIT(1));
await g.page.reload();
await g.page.waitForTimeout(1500);
const cdp = await setupSlow(g.page, 1);
await g.page.waitForTimeout(4000);
const probe = () => g.page.evaluate(() => ({ v: performance.now() / 1000, ft: window.__app.world.time, rate: window.__rate() }));
let a = await probe(); await g.page.waitForTimeout(2000); let b = await probe();
console.log('rate1 idle: virtual', (b.v - a.v).toFixed(2), 'game', (b.ft - a.ft).toFixed(2));
await setRate(g.page, cdp, 0.2);
a = await probe(); await g.page.waitForTimeout(3000); b = await probe();
console.log('rate0.2 idle: virtual', (b.v - a.v).toFixed(2), 'game', (b.ft - a.ft).toFixed(2));
a = await probe();
const seg = await captureSegment(g.page, cdp, '/tmp/claude-0/cc', 'x', { maxSec: 1.5 });
b = await probe();
console.log('rate0.2 capturing: virtual', (b.v - a.v).toFixed(2), 'game', (b.ft - a.ft).toFixed(2), 'frames', seg.frames.length);
await g.close();
